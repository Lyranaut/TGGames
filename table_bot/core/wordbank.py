def draw_party_words(n: int) -> list:
    """n уникальных слов из общего пула (без повторов внутри одной игры)."""
    if n <= len(PARTY_WORDS):
        return random.sample(PARTY_WORDS, n)
    return [random.choice(PARTY_WORDS) for _ in range(n)]


def draw_hangman_word() -> str:
    return random.choice(HANGMAN_WORDS)
