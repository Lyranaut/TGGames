def random_whoami_identities(n: int) -> list:
    if n <= len(WHOAMI_IDENTITIES):
        return random.sample(WHOAMI_IDENTITIES, n)
    return [random.choice(WHOAMI_IDENTITIES) for _ in range(n)]


def draw_quiz_questions(n: int) -> list:
    pool = list(QUIZ_QUESTIONS)
    random.shuffle(pool)
    return pool[:n]

