from __future__ import annotations

from aiogram import Router, F
from aiogram.filters import Command
from aiogram.types import Message

router = Router()

HELP_TEXT = (
    "🎲 <b>Бот Бога Настолок — список игр и команд</b>\n\n"
    "В одном чате (ветке) одновременно может идти только одна игра — "
    "команда следующей игры не сработает, пока текущая не закончится.\n\n"
    "🐊 <b>/crocodile</b> — Крокодил. Ведущий получает слово в личку и "
    "объясняет его словами в чат (без однокоренных), бот сам ловит верный "
    "ответ и сразу передаёт слово следующему ведущему.\n\n"
    "🎯 <b>/hangman</b> — Виселица. Открытая игра для всех в чате, "
    "регистрация не нужна — пишите буквы или слово целиком прямо в чат. "
    "<code>/hangman_stop</code> — остановить досрочно.\n\n"
    "🎭 <b>/whoami</b> — Кто я? Каждому достаётся тайная личность, которую "
    "видят все, кроме него самого. Задавайте вопросы да/нет в чат, "
    "отгадывать — командой <code>/answer ваш ответ</code>. "
    "<code>/whoami_stop</code> — закончить досрочно.\n\n"
    "🗣 <b>/elias</b> — Элиас 2 на 2 (командный Крокодил словами). Нужно "
    "ровно 4 игрока, команды по 2 составляются случайно, счёт по верным "
    "словам ведётся автоматически.\n\n"
    "😂 <b>/funprompt</b> — «Придумай смешнее» (в духе Quiplash/Fibbage из "
    "Jackbox Party Pack). Каждый раунд — фраза с пропуском, вы дописываете "
    "смешной вариант в личке, потом все голосуют анонимно за самый смешной.\n\n"
    "🧠 <b>/quiz</b> — Викторина. Вопросы общих знаний прямо в чат, кто "
    "первым написал верный ответ — получает очко. Присоединяться заранее "
    "не обязательно.\n\n"
    "Перед началом каждой игры (кроме открытых Виселицы и Викторины) бот "
    "показывает короткие правила прямо в сообщении с кнопкой «Вступить»."
)


@router.message(Command("help"))
async def cmd_help(message: Message):
    await message.answer(HELP_TEXT)


@router.message(Command("start"), F.chat.type.in_({"group", "supergroup"}))
async def cmd_start_group(message: Message):
    await message.answer(HELP_TEXT)
