FULL_ORDER = ["profession", "health", "hobby", "phobia", "trait", "baggage", "fact", "special"]


def _sample_or_repeat(pool: list, n: int) -> list:
    """n уникальных значений, если хватает пула, иначе — со случайным повтором."""
    if n <= len(pool):
        return random.sample(pool, n)
    return [random.choice(pool) for _ in range(n)]


def _generate_age() -> str:
    return str(random.randint(6, 78))


def deal_cards(players: list) -> None:
    n = len(players)
    genders = [random.choice(GENDERS) for _ in range(n)]
    ages = [_generate_age() for _ in range(n)]
    professions = _sample_or_repeat(PROFESSIONS, n)
    healths = _sample_or_repeat(HEALTH, n)
    hobbies = _sample_or_repeat(HOBBIES, n)
    phobias = _sample_or_repeat(PHOBIAS, n)
    traits = _sample_or_repeat(TRAITS, n)
    baggages = _sample_or_repeat(BAGGAGE, n)
    facts = _sample_or_repeat(FACTS, n)
    specials = _sample_or_repeat(SPECIALS, n)

    for i, player in enumerate(players):
        player.cards = {
            "gender": genders[i],
            "age": ages[i],
            "profession": professions[i],
            "health": healths[i],
            "hobby": hobbies[i],
            "phobia": phobias[i],
            "trait": traits[i],
            "baggage": baggages[i],
            "fact": facts[i],
            "special": specials[i],
        }


def format_full_card(cards: dict) -> str:
    lines = [f"{CARD_LABELS['gender']}: {cards['gender']}, {CARD_LABELS['age']}: {cards['age']} лет"]
    for key in FULL_ORDER:
        lines.append(f"{CARD_LABELS[key]}: {cards[key]}")
    return "\n".join(lines)


def format_round_reveal(cards: dict, keys: list) -> str:
    lines = []
    for key in keys:
        if key == "age":
            lines.append(f"{CARD_LABELS['age']}: {cards['age']} лет")
        else:
            lines.append(f"{CARD_LABELS[key]}: {cards[key]}")
    return "\n".join(lines)